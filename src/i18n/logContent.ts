export function getLogCopy(
  logId: string,
  enTitle: string,
  enBody: string,
  locale: Locale,
): LogCopy {
  if (locale === 'en') {
    return { title: enTitle, body: enBody };
  }
  const localized = LOCALIZED[locale]?.[logId];
  if (localized) {
    return localized;
  }
  return { title: enTitle, body: enBody };
}
